N_DISAGREEMENTS_TO_SAMPLE = 30
DISAGREEMENT_CONTEXT_BARS = 50

UNKNOWN_LABEL = "unknown"


# ---------------------------------------------------------------------------
# Weak-label rule engine
# ---------------------------------------------------------------------------

@dataclass
class WeakLabelFeatures:
    """The auxiliary series the weak-label rules need."""

    adx14: pd.Series
    atr14: pd.Series
    sma20: pd.Series
    realized_vol20: pd.Series
    rv_pct_low_30: pd.Series       # rolling 30th percentile (chop floor)
    rv_pct_high_95: pd.Series      # rolling 95th percentile (vol_spike floor)
    news_proximity: pd.Series      # 0/1; nan when calendar unavailable


def _rolling_percentile_floor(series: pd.Series, window: int, q: float) -> pd.Series:
    """Rolling `q`-quantile of `series`, computed over `window` bars."""
    return series.rolling(window, min_periods=max(20, window // 4)).quantile(q)


def build_weak_label_features(
    df: pd.DataFrame,
    *,
    rv_window: int = 500,
    news_calendar: pd.Series | None = None,
) -> WeakLabelFeatures:
    """Compute the indicators the weak-label rules read.

    `news_calendar`: optional bool series aligned to `df.index`; True
    when the bar is within ±2 H4 bars of a high-impact USD/EUR event.
    When omitted (the common case on this Mac host — FF feed is
    current-week only and 2024 events are not cached), the news rule
    abstains.
    """
    adx_val = adx(df, period=14)["adx"]
    atr_val = atr(df, period=14)
    sma20 = df["close"].rolling(20).mean()
    log_ret = np.log(df["close"] / df["close"].shift(1))
    rv20 = log_ret.rolling(20).std()
    rv_pct_low = _rolling_percentile_floor(rv20, rv_window, 0.30)
    rv_pct_high = _rolling_percentile_floor(rv20, rv_window, 0.95)
    if news_calendar is None:
        news = pd.Series(np.nan, index=df.index, dtype=float)
    else:
        news = news_calendar.astype(float)
    return WeakLabelFeatures(
        adx14=adx_val,
        atr14=atr_val,
        sma20=sma20,
        realized_vol20=rv20,
        rv_pct_low_30=rv_pct_low,
        rv_pct_high_95=rv_pct_high,
        news_proximity=news,
    )


def weak_label_row(
    *,
    close: float,
    adx14: float,
    atr14: float,
    sma20: float,
    rv20: float,
    rv_pct_low_30: float,
    rv_pct_high_95: float,
    news_flag: float,
) -> str:
    """Apply the priority-ordered weak-label rules to a single bar.

    Priority: `news > vol_spike > trending > chop > unknown`. Any
    NaN input that the rule depends on demotes the rule (the rule
    abstains); the next rule in priority order gets the chance. The
    final fallback is `unknown` (bar excluded from agreement F1).
    """
    # `news` — only fires when the calendar series is non-NaN.
    if np.isfinite(news_flag) and news_flag > 0.5:
        return "news"

    # `vol_spike` — needs both rv and adx; rv must clear the rolling
    # 95th percentile AND adx must be below 25.
    if (
        np.isfinite(rv20)
        and np.isfinite(rv_pct_high_95)
        and np.isfinite(adx14)
        and rv20 > rv_pct_high_95
        and adx14 < 25
    ):
        return "vol_spike"

    # `trending` — adx high AND close pulling away from SMA20.
    if (
        np.isfinite(adx14)
        and np.isfinite(atr14)
        and np.isfinite(sma20)
        and atr14 > 0
        and adx14 > 25
        and abs(close - sma20) > 0.5 * atr14
    ):
        return "trending"

    # `chop` — adx low AND rv compressed.
    if (
        np.isfinite(adx14)
        and np.isfinite(rv20)
        and np.isfinite(rv_pct_low_30)
        and adx14 < 15
        and rv20 < rv_pct_low_30
    ):
        return "chop"

    return UNKNOWN_LABEL


def weak_label_dataframe(
    df: pd.DataFrame,
    *,
    rv_window: int = 500,
    news_calendar: pd.Series | None = None,
) -> pd.Series:
    """Vectorised wrapper around `weak_label_row` for a full bar frame."""
    feats = build_weak_label_features(
        df, rv_window=rv_window, news_calendar=news_calendar
    )
    labels = []
    for idx in df.index:
        close = float(df.at[idx, "close"])
        labels.append(weak_label_row(
            close=close,
            adx14=float(feats.adx14.get(idx, np.nan)),
            atr14=float(feats.atr14.get(idx, np.nan)),
            sma20=float(feats.sma20.get(idx, np.nan)),
            rv20=float(feats.realized_vol20.get(idx, np.nan)),
            rv_pct_low_30=float(feats.rv_pct_low_30.get(idx, np.nan)),
            rv_pct_high_95=float(feats.rv_pct_high_95.get(idx, np.nan)),
            news_flag=float(feats.news_proximity.get(idx, np.nan)),
        ))
    return pd.Series(labels, index=df.index, name="weak_label", dtype="string")


# ---------------------------------------------------------------------------
# Disagreement sampling
# ---------------------------------------------------------------------------

def sample_disagreements(
    *,
    df: pd.DataFrame,
    weak: pd.Series,
    predicted: pd.Series,
    n_samples: int = N_DISAGREEMENTS_TO_SAMPLE,
    context_bars: int = DISAGREEMENT_CONTEXT_BARS,
    seed: int = 42,
) -> pd.DataFrame:
    """Pick `n_samples` random disagreement bars; return a long-format CSV.

    Schema:

        sample_idx, anchor_ts, weak_label, predicted_label,
        offset (-context..0), ts, open, high, low, close, volume

    `offset = 0` is the anchor bar (the disagreement); negative offsets
    are the preceding context. Bars without enough history are skipped
    so every sample contains exactly `context_bars + 1` rows.
    """
    mask = (weak != UNKNOWN_LABEL) & (weak != predicted)
    candidates = df.index[mask.reindex(df.index, fill_value=False)]
    if len(candidates) == 0:
        return pd.DataFrame(
            columns=[
                "sample_idx", "anchor_ts", "weak_label", "predicted_label",
                "offset", "ts", "open", "high", "low", "close", "volume",
            ]
        )
    rng = np.random.default_rng(seed)
    n_pick = min(n_samples, len(candidates))
    pick_pos = rng.choice(len(candidates), size=n_pick, replace=False)
    pick_pos.sort()
    rows: list[dict] = []
    for sample_idx, c_pos in enumerate(pick_pos):
        anchor_ts = candidates[c_pos]
        anchor_iloc = df.index.get_loc(anchor_ts)
        start_iloc = anchor_iloc - context_bars
        if start_iloc < 0:
            continue
        window = df.iloc[start_iloc:anchor_iloc + 1]
        for off, (ts, bar) in enumerate(window.iterrows()):
            rows.append({
                "sample_idx": int(sample_idx),
                "anchor_ts": anchor_ts.isoformat(),
                "weak_label": str(weak.loc[anchor_ts]),
                "predicted_label": str(predicted.loc[anchor_ts]),
                "offset": int(off - context_bars),
                "ts": ts.isoformat(),
                "open": float(bar["open"]),
                "high": float(bar["high"]),
                "low": float(bar["low"]),
                "close": float(bar["close"]),
                "volume": float(bar.get("volume", 0.0)),
            })
    return pd.DataFrame(rows)


