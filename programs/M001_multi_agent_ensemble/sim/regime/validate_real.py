def load_news_calendar(
    index: pd.DatetimeIndex,
    *,
    cache_path: Path | None = None,
    window_bars: int = 2,
) -> pd.Series | None:
    """Backward-compat proxy for the historical current-week-only path.

    2026-07-01 Phase M rewire: this function now delegates to
    :func:`sim.regime.news_calendar.load_news_calendar` (Φ5 historical
    archive adapter) per spec §5.2. ``cache_path`` is silently
    forwarded as ``archive_root``. Legacy signature (``index``,
    ``cache_path``, ``window_bars``) is preserved; the new
    keyword-only arguments carry the pre-redesign filter defaults
    (USD + EUR, high-impact only, Dukascopy primary).

    Kept as a thin proxy so the weak-label rule in ``label_by_features``
    (§ ~line 90) can continue calling ``load_news_calendar`` with the
    original signature. Any new caller SHOULD depend on
    ``sim.regime.news_calendar.load_news_calendar`` directly.
    """
    from programs.M001_multi_agent_ensemble.sim.regime.news_calendar import (
        load_news_calendar as _load_v2,
    )
    return _load_v2(
        index,
        archive_root=cache_path,
        window_bars=window_bars,
        currencies=("USD", "EUR"),
        importance_min=3,
        sources=("DK",),
    )


# ---------------------------------------------------------------------------
# Validation pipeline
# ---------------------------------------------------------------------------

def run_validation(
    *,
    parquet_path: Path,
    model_path: Path,
    window_start: str = "2024-01-01",
    window_end: str = "2025-01-01",
    seed: int = 42,
    news_cache_path: Path | None = None,
    out_validation: Path | None = None,
    out_disagreements: Path | None = None,
) -> dict:
    """Run the weak-label validation pipeline end-to-end.

    Returns the result dict (also written to `out_validation` when set).
    Falls back to the most-recent year of bars when the requested
    window is empty in the parquet cache; the substitution is recorded
    in `manifest.window_substitution`.
    """
    from sklearn.metrics import (  # local import keeps the module light
        classification_report,
        confusion_matrix,
        f1_score,
    )

    bars = pd.read_parquet(parquet_path)
    if bars.index.tz is None:
        bars.index = bars.index.tz_localize("UTC")

    window = bars[(bars.index >= window_start) & (bars.index < window_end)]
    substitution_note: str | None = None
    if len(window) < 200:
        # Fallback: take the last calendar year of available bars.
        # Documented in the manifest so callers know the substitution
        # happened.
        last_ts = bars.index.max()
        fallback_start = (last_ts - pd.DateOffset(years=1)).normalize()
        window = bars[bars.index >= fallback_start]
        substitution_note = (
            f"requested {window_start}..{window_end} had "
            f"{len(bars[(bars.index >= window_start) & (bars.index < window_end)])} "
            f"bars; substituted last 12 months ({fallback_start.isoformat()} → "
            f"{last_ts.isoformat()})"
        )

    if len(window) < 50:
        raise RuntimeError(
            f"parquet {parquet_path} yields only {len(window)} bars in any "
            "1y window — cannot validate"
        )

    # News calendar (None on this Mac host — see docstring).
    news_flag = load_news_calendar(window.index, cache_path=news_cache_path)
    news_available = news_flag is not None and (news_flag > 0).any()

    # Weak labels and classifier predictions on the same index.
    weak = weak_label_dataframe(window, news_calendar=news_flag)
    clf = RegimeClassifier.load(model_path)
    feats = extract_features(window).fillna(0.0)
    pred = pd.Series(clf.predict(feats), index=window.index,
                     name="predicted", dtype="string")

    # Scope: bars where the weak labeller voted (not unknown). The
    # agreement F1 below is computed strictly on this subset.
    scope = weak != UNKNOWN_LABEL
    n_total = int(len(window))
    n_scored = int(scope.sum())
    weak_scored = weak[scope].to_list()
    pred_scored = pred[scope].to_list()

    agreement_f1 = float(
        f1_score(
            weak_scored, pred_scored,
            labels=list(REGIMES), average="macro", zero_division=0,
        )
    ) if n_scored else 0.0
    report = classification_report(
        weak_scored, pred_scored,
        labels=list(REGIMES), output_dict=True, zero_division=0,
    ) if n_scored else {r: {"precision": 0.0, "recall": 0.0,
                            "f1-score": 0.0, "support": 0} for r in REGIMES}
    cm = confusion_matrix(
        weak_scored, pred_scored, labels=list(REGIMES),
    ).tolist() if n_scored else [[0] * len(REGIMES) for _ in REGIMES]

    # Sampled disagreements for human review.
    disagreements = sample_disagreements(
        df=window, weak=weak, predicted=pred, seed=seed,
    )
    if out_disagreements is not None:
        out_disagreements.parent.mkdir(parents=True, exist_ok=True)
        disagreements.to_csv(out_disagreements, index=False)
    n_disagreements_total = int(((weak != UNKNOWN_LABEL) & (weak != pred)).sum())

    # Class-distribution counts (sanity check; not a metric).
    weak_class_counts = (
        weak[scope].value_counts().reindex(list(REGIMES), fill_value=0).to_dict()
    )
    pred_class_counts = (
        pred[scope].value_counts().reindex(list(REGIMES), fill_value=0).to_dict()
    )

    result = {
        "manifest": {
            "parquet_path": str(parquet_path),
            "model_path": str(model_path),
            "window_start": str(window.index.min()),
            "window_end": str(window.index.max()),
            "requested_window": [window_start, window_end],
            "window_substitution": substitution_note,
            "seed": int(seed),
            "rv_window": 500,
            "news_calendar_available": bool(news_available),
            "generated_at_utc": datetime.now(timezone.utc).isoformat(),
            "_note": (
                "Weak-label agreement F1 is NOT ground-truth F1. The"
                " heuristic and the classifier disagree on a real label"
                " is the trigger to escalate to hand-labelling; see"
                " sim/regime/README.md for the interpretation guide."
            ),
        },
        "counts": {
            "n_total_bars": n_total,
            "n_scored_bars": n_scored,
            "n_unknown_weak_label": int((weak == UNKNOWN_LABEL).sum()),
            "n_disagreements_total": n_disagreements_total,
            "n_disagreements_sampled": int(disagreements["sample_idx"].nunique())
            if not disagreements.empty else 0,
            "weak_label_class_counts": {k: int(v) for k, v in weak_class_counts.items()},
            "predicted_class_counts": {k: int(v) for k, v in pred_class_counts.items()},
        },
        "metrics": {
            "agreement_f1_macro": agreement_f1,
            "per_class": {
                r: {
                    "precision": float(report[r]["precision"]),
                    "recall": float(report[r]["recall"]),
                    "f1": float(report[r]["f1-score"]),
                    "support": int(report[r]["support"]),
                }
                for r in REGIMES
            },
            "confusion_matrix_rows_weak_cols_pred": cm,
            "label_order": list(REGIMES),
        },
        "gate": {
            "threshold_agreement_f1": float(WEAK_GATE_AGREEMENT_F1),
            "pass": bool(agreement_f1 >= WEAK_GATE_AGREEMENT_F1),
            "note": (
                "Pass here means the classifier is at least as good as"
                " the rule-based heuristic on bars where the heuristic"
                " votes confidently. It does NOT clear the Φ2→Φ3 G4 gate,"
                " which still requires hand-labelled validation."
            ),
        },
    }
    if out_validation is not None:
        out_validation.parent.mkdir(parents=True, exist_ok=True)
        out_validation.write_text(
            json.dumps(result, indent=2, sort_keys=True),
            encoding="utf-8",
        )
    return result


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Weak-label real-data validation for the regime classifier.",
    )
    parser.add_argument("--parquet", type=Path, default=DEFAULT_PARQUET)
    parser.add_argument("--model", type=Path, default=DEFAULT_MODEL)
    parser.add_argument("--window-start", type=str, default="2024-01-01")
    parser.add_argument("--window-end", type=str, default="2025-01-01")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--out-validation", type=Path, default=DEFAULT_VALIDATION_OUT,
    )
    parser.add_argument(
        "--out-disagreements", type=Path, default=DEFAULT_DISAGREEMENTS_OUT,
    )
    parser.add_argument("--news-cache-path", type=Path, default=None)
    args = parser.parse_args(argv)

    result = run_validation(
        parquet_path=args.parquet,
        model_path=args.model,
        window_start=args.window_start,
        window_end=args.window_end,
        seed=args.seed,
        news_cache_path=args.news_cache_path,
        out_validation=args.out_validation,
        out_disagreements=args.out_disagreements,
    )
    print(json.dumps(
        {
            "agreement_f1_macro": result["metrics"]["agreement_f1_macro"],
            "n_total_bars": result["counts"]["n_total_bars"],
            "n_scored_bars": result["counts"]["n_scored_bars"],
            "n_disagreements_total": result["counts"]["n_disagreements_total"],
            "n_disagreements_sampled": result["counts"]["n_disagreements_sampled"],
            "gate_pass_against_weak_labels": result["gate"]["pass"],
            "window_substitution": result["manifest"]["window_substitution"],
        },
        indent=2,
    ))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
