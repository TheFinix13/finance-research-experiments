"""Regime classifier real-data validation (weak-label agreement).

Φ2→Φ3 gate (G4) blocker:

The Φ2.5 classifier trained on synthetic OHLCV and self-reported
holdout macro F1 ≈ 0.999. That score is **not** a meaningful gate
check because the labels were generated by the same rule the trainer
fits to (perfect circularity). True F1 requires hand-labelled
validation bars, which is a separate Φ3 deliverable.

This script provides the *interim* check between "synthetic F1" and
"hand-labelled F1": **weak-label agreement** against a small set of
heuristic rules on real EURUSD H4 bars. The number it prints is
**not** ground-truth F1 — it answers a strictly weaker question:

    Does the trained classifier agree with the heuristic on bars
    where the heuristic gives a confident vote?

A high agreement number means the classifier is at least as
discriminative as the heuristic. A low number flags that the
classifier is doing something different (possibly worse) and is the
trigger to escalate to hand-labelling — see `sim/regime/README.md`
for the interpretation guide.

Weak-label rules (this file is the source of truth):

* trending : ADX(14) > 25  AND  |close − SMA20| > 0.5 × ATR(14)
* chop     : ADX(14) < 15  AND  realized_vol(20) < 30th pct (rolling 500)
* vol_spike: realized_vol(20) > 95th pct (rolling 500)  AND  ADX(14) < 25
* news     : within ±2 H4 bars of a high-impact ForexFactory event
             on EUR or USD; **unavailable** when the production
             calendar cache has no events for the validation window
             (FF feed is current-week only). When unavailable the rule
             abstains and the bar is left to one of the other three
             classes (or `unknown`).

Output artefacts (under `programs/.../sim/regime/`):

* `validation_2024_eurusd_h4.json` — confusion matrix, per-class
  precision/recall/F1, agreement F1, n samples, gate threshold (0.5),
  pass/fail flag, manifest (seed, parquet path, model path, date).
* `disagreements_for_review.csv` — 30 sampled bars where the
  classifier disagreed with a non-unknown weak label, each row
  carrying 50 bars of OHLC context for future human labelling.
"""
